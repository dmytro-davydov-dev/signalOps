"""Export versioned JSON Schemas, OpenAPI, and the generated frontend status module.

Run `uv run signalops export-schemas` after changing a contract. A test fails
while the committed files differ from what this module renders. Rewriting an
existing schema file with a structurally breaking change is refused: add a new
contract version instead (see docs/events.md, "Versioning rules").
"""

import json
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from pydantic import BaseModel, SecretStr, TypeAdapter

from signalops.contracts.adapters import ADAPTER_INPUTS
from signalops.contracts.checkpoints import CHECKPOINT_SCHEMA_VERSION, StepCheckpoint
from signalops.contracts.compatibility import breaking_changes
from signalops.contracts.diagnosis import Diagnosis, DiagnosisStatus
from signalops.contracts.events import EVENT_PAYLOADS, EventEnvelope
from signalops.contracts.evidence import NormalizedSignal
from signalops.contracts.incidents import IncidentDetail, IncidentPage, IncidentSummary
from signalops.contracts.ingestion import IngestRequest, IngestResponse
from signalops.contracts.investigations import (
    DIAGNOSIS_STATUS_BY_INVESTIGATION_STATUS,
    InvestigationView,
)
from signalops.contracts.tools import TOOL_RESULT_ADAPTER, ToolFailure
from signalops.contracts.workflow import TERMINAL_INVESTIGATION_STATUSES, InvestigationStatus

REPOSITORY_ROOT = Path(__file__).resolve().parents[3]
SCHEMA_DIR = Path("backend/signalops/contracts/schemas")
WEB_STATUS_MODULE = Path("apps/web/src/api/generated/investigationStatus.ts")
JSON_SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"


class BreakingChangeError(RuntimeError):
    def __init__(self, breaks: dict[Path, list[str]]) -> None:
        lines = [f"{path}: {change}" for path, changes in breaks.items() for change in changes]
        super().__init__(
            "breaking contract changes; add a new version instead:\n" + "\n".join(lines)
        )
        self.breaks = breaks


@dataclass(frozen=True)
class Artifact:
    path: Path
    render: Callable[[], str]
    # JSON Schema files are checked for breaking changes before being rewritten.
    is_schema: bool = True


def _json(document: Any) -> str:
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _schema(source: type[BaseModel] | TypeAdapter[Any]) -> Callable[[], str]:
    def render() -> str:
        if isinstance(source, TypeAdapter):
            schema = source.json_schema()
        else:
            schema = source.model_json_schema()
        return _json({"$schema": JSON_SCHEMA_DIALECT, **schema})

    return render


def _openapi() -> str:
    from signalops.api.app import create_app
    from signalops.config import Settings

    # The document depends only on routes; no connection is opened.
    settings = Settings(database_url=SecretStr("postgresql+psycopg://export@localhost/export"))
    return _json(create_app(settings).openapi())


def _status_mapping() -> str:
    return _json(
        {
            "investigation_statuses": list(InvestigationStatus),
            "terminal_investigation_statuses": [
                s for s in InvestigationStatus if s in TERMINAL_INVESTIGATION_STATUSES
            ],
            "diagnosis_statuses": list(DiagnosisStatus),
            "diagnosis_status_by_investigation_status": DIAGNOSIS_STATUS_BY_INVESTIGATION_STATUS,
        }
    )


def _ts_list(values: Iterable[str]) -> str:
    return "".join(f"  {json.dumps(value)},\n" for value in values)


def _web_status_module() -> str:
    statuses = list(InvestigationStatus)
    terminal = [s for s in statuses if s in TERMINAL_INVESTIGATION_STATUSES]
    mapping = "".join(
        f"  {status}: {json.dumps(diagnosis)},\n"
        for status, diagnosis in DIAGNOSIS_STATUS_BY_INVESTIGATION_STATUS.items()
    )
    return (
        "// Generated by `uv run signalops export-schemas` from\n"
        "// backend/signalops/contracts/investigations.py. Do not edit.\n"
        "\n"
        f"export const INVESTIGATION_STATUSES = [\n{_ts_list(statuses)}] as const;\n"
        "\n"
        "export type InvestigationStatus = (typeof INVESTIGATION_STATUSES)[number];\n"
        "\n"
        f"export const DIAGNOSIS_STATUSES = [\n{_ts_list(list(DiagnosisStatus))}] as const;\n"
        "\n"
        "export type DiagnosisStatus = (typeof DIAGNOSIS_STATUSES)[number];\n"
        "\n"
        "export const TERMINAL_INVESTIGATION_STATUSES: readonly InvestigationStatus[] = [\n"
        f"{_ts_list(terminal)}];\n"
        "\n"
        "export const DIAGNOSIS_STATUS_BY_INVESTIGATION_STATUS: Readonly<\n"
        "  Record<InvestigationStatus, DiagnosisStatus | null>\n"
        "> = {\n"
        f"{mapping}}};\n"
    )


def artifacts() -> list[Artifact]:
    found = [
        Artifact(
            SCHEMA_DIR / "events" / f"{event_type}.v{version}.json",
            _schema(EventEnvelope[payload]),  # type: ignore[valid-type]
        )
        for (event_type, version), payload in EVENT_PAYLOADS.items()
    ]
    found += [
        Artifact(SCHEMA_DIR / "adapters" / f"{kind}.v1.json", _schema(model))
        for kind, model in ADAPTER_INPUTS.items()
    ]
    found += [
        Artifact(SCHEMA_DIR / "evidence" / "normalized-signal.v1.json", _schema(NormalizedSignal)),
        Artifact(SCHEMA_DIR / "ingestion" / "ingest-request.v1.json", _schema(IngestRequest)),
        Artifact(SCHEMA_DIR / "ingestion" / "ingest-response.v1.json", _schema(IngestResponse)),
        Artifact(SCHEMA_DIR / "incidents" / "incident-summary.v1.json", _schema(IncidentSummary)),
        Artifact(SCHEMA_DIR / "incidents" / "incident-detail.v1.json", _schema(IncidentDetail)),
        Artifact(SCHEMA_DIR / "incidents" / "incident-page.v1.json", _schema(IncidentPage)),
        Artifact(
            SCHEMA_DIR / "investigations" / "investigation.v1.json", _schema(InvestigationView)
        ),
        Artifact(
            SCHEMA_DIR / "investigations" / "status-mapping.v1.json",
            _status_mapping,
            is_schema=False,
        ),
        Artifact(SCHEMA_DIR / "diagnosis" / "diagnosis.v1.json", _schema(Diagnosis)),
        Artifact(
            SCHEMA_DIR / "workflow" / f"step-checkpoint.v{CHECKPOINT_SCHEMA_VERSION}.json",
            _schema(StepCheckpoint),
        ),
        Artifact(SCHEMA_DIR / "tools" / "tool-result.v1.json", _schema(TOOL_RESULT_ADAPTER)),
        Artifact(SCHEMA_DIR / "tools" / "tool-failure.v1.json", _schema(ToolFailure)),
        Artifact(SCHEMA_DIR / "openapi.v1.json", _openapi, is_schema=False),
        Artifact(WEB_STATUS_MODULE, _web_status_module, is_schema=False),
    ]
    return found


def render_all() -> dict[Path, str]:
    return {artifact.path: artifact.render() for artifact in artifacts()}


def stale_paths(root: Path = REPOSITORY_ROOT) -> list[Path]:
    """Artifacts whose committed content differs from the current contracts,
    plus files in the schema directory that no contract produces any more."""
    rendered = render_all()
    stale = [
        path
        for path, content in rendered.items()
        if not (root / path).exists() or (root / path).read_text() != content
    ]
    for existing in sorted((root / SCHEMA_DIR).rglob("*.json")):
        relative = existing.relative_to(root)
        if relative not in rendered:
            stale.append(relative)
    return stale


def write_all(root: Path = REPOSITORY_ROOT, *, allow_breaking: bool = False) -> list[Path]:
    """Write changed artifacts and return their paths.

    Nothing is written if an existing schema would change incompatibly, unless
    `allow_breaking` is set (only for unreleased contracts).
    """
    pending: dict[Path, str] = {}
    breaks: dict[Path, list[str]] = {}
    for artifact in artifacts():
        content = artifact.render()
        target = root / artifact.path
        if target.exists() and target.read_text() == content:
            continue
        if artifact.is_schema and target.exists():
            changes = breaking_changes(json.loads(target.read_text()), json.loads(content))
            if changes:
                breaks[artifact.path] = changes
        pending[artifact.path] = content
    if breaks and not allow_breaking:
        raise BreakingChangeError(breaks)
    for path, content in pending.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    return sorted(pending)
